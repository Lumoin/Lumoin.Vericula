        //r1-55: the reader's LoadOptions.SetLineInfo means a failing document's root
        //element carries a real position; without wiring that into the Location the
        //diagnostic reports, this assertion would see Location.None instead of a real
        //external-file span naming the source file and its first line.
        var result = RunGenerator("""
