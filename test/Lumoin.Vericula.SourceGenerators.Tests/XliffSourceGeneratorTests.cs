                </xliff>
                """),
            ("wallet.pt-BR.xliff", """
                <xliff xmlns="urn:oasis:names:tc:xliff:document:2.0" version="2.0" srcLang="en" trgLang="pt-BR">
                  <file id="wallet">
                    <unit id="Color">
                      <segment>
                        <source>Color</source>
                        <target>Cor (BR)</target>
                      </segment>
                    </unit>
                  </file>
                </xliff>
                """),
            ("wallet.pt-PT.xliff", """
                <xliff xmlns="urn:oasis:names:tc:xliff:document:2.0" version="2.0" srcLang="en" trgLang="pt-PT">
