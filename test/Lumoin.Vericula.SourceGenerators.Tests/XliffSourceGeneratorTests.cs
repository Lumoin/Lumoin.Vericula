    [TestMethod]
    public void TheParsedDocumentAndCollectedModelStepsStayCachedAcrossAnUnrelatedChange()
    {
        //Kills a mutant that reverts XliffDocumentModel.Units from EquatableArray<UnitModel>
        //back to ImmutableArray<UnitModel>: ImmutableArray's own equality compares the
        //wrapped array by reference, so a genuinely re-parsed but content-equal document
        //would then report Modified instead of Unchanged, and this assertion would fail.
        var generator = new XliffSourceGenerator();
        var originalText = new MemoryAdditionalText("wallet.fi.xliff", TwoLanguageXliff);
        var driverOptions = new GeneratorDriverOptions(IncrementalGeneratorOutputKind.None, trackIncrementalGeneratorSteps: true);
        var driver = CSharpGeneratorDriver.Create(
            generators: [generator.AsSourceGenerator()],
            additionalTexts: [originalText],
            parseOptions: null,
            optionsProvider: null,
            driverOptions: driverOptions);
        var compilation = CSharpCompilation.Create(
            assemblyName: "Cacheability",
            syntaxTrees: [],
            references: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)]);

        driver = (CSharpGeneratorDriver)driver.RunGenerators(compilation, TestContext.CancellationToken);

        //The same file, cosmetically re-supplied: a fresh AdditionalText instance whose only
        //textual difference from the original is a comment the parser ignores, so the parsed
        //model must compare equal to the previous run's model for the cache to stay hot. An
        //unrelated syntax tree is added to the compilation too, so nothing about this change
        //is specific to the XLIFF file's own content.
        var refreshedText = new MemoryAdditionalText("wallet.fi.xliff", TwoLanguageXliffWithAnIrrelevantComment);
        driver = (CSharpGeneratorDriver)driver.ReplaceAdditionalText(originalText, refreshedText);
        var nextCompilation = compilation.AddSyntaxTrees(
            CSharpSyntaxTree.ParseText("internal sealed class UnrelatedType { }", cancellationToken: TestContext.CancellationToken));
        driver = (CSharpGeneratorDriver)driver.RunGenerators(nextCompilation, TestContext.CancellationToken);

        ImmutableDictionary<string, ImmutableArray<IncrementalGeneratorRunStep>> trackedSteps =
            driver.GetRunResult().Results[0].TrackedSteps;
        AssertCachedOrUnchanged(trackedSteps, WellKnownGeneratorSteps.ParsedDocument);
        AssertCachedOrUnchanged(trackedSteps, WellKnownGeneratorSteps.CollectedModel);
    }

    [TestMethod]
    public void ALineBreakInSourceTextIsStrippedFromTheDocCommentAndKeptVerbatimInTheStringLiteral()
    {
        //r1-93: a CRLF, a LINE SEPARATOR (U+2028), a doc-comment close, a triple slash, a
        //quote and a brace inside <source> used to spill out of the single-line ///
        //summary and become code; if that regressed, either the generated file would fail
        //to compile (asserted by EmitAndLoad below) or the returned text would not be the
        //original, unbroken string, because the string literal is unaffected but a
        //surviving line break would have split the source into two statements.
        string xliff = """
            <xliff xmlns="urn:oasis:names:tc:xliff:document:2.0" version="2.0" srcLang="en">
              <file id="wallet">
                <unit id="Injection">
                  <segment>
                    <source>Line one&#13;&#10;Line two&#8232;Line three */ /// "quoted" { braces }</source>
                  </segment>
                </unit>
              </file>
            </xliff>
            """;
        (Type translationsType, AssemblyLoadContext context) = EmitAndLoad(xliff, "SecurityInjection", TestContext.CancellationToken);
        try
        {
            string expected = "Line one\r\nLine two\u2028Line three */ /// \"quoted\" { braces }";

            Assert.AreEqual(expected, GetAccessor(translationsType, "Injection"));
        }
        finally
        {
            context.Unload();
        }
    }

    [TestMethod]
    public void AUnitIdThatIsAKeywordGetsAVerbatimIdentifierAccessor()
    {
        //r1-47: "class" passes SyntaxFacts.IsValidIdentifier but is a reserved keyword; the
        //fix escapes it as @class instead of skipping it. Without the escape, the emitted
        //`public static string class => ...;` would fail to compile, and EmitAndLoad would
        //fail the assertion below instead of finding the property under its escaped name.
        string xliff = """
            <xliff xmlns="urn:oasis:names:tc:xliff:document:2.0" version="2.0" srcLang="en">
              <file id="wallet">
                <unit id="class">
                  <segment>
                    <source>Reserved word text.</source>
                  </segment>
                </unit>
              </file>
            </xliff>
            """;
        var result = RunGenerator(xliff, "Keyword", TestContext.CancellationToken);

        Assert.HasCount(0, result.Diagnostics);
        string code = result.Results[0].GeneratedSources[0].SourceText.ToString();
        Assert.Contains("public static string @class => Resolve(\"class\");", code, StringComparison.Ordinal);
    }

    [TestMethod]
