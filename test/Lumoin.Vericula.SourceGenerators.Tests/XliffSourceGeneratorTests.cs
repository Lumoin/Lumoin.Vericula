    [TestMethod]
    public void PortugueseBrazilAndPortugalKeepSeparateTranslationTables()
    {
        //r1-49: keying by the primary subtag alone ("pt") would let pt-PT overwrite
        //pt-BR (or the reverse, depending on provider order); keying by the full tag
        //keeps LanguagePtBR and LanguagePtPT distinct, and each culture resolves its own.
        var files = new[]
        {
            ("wallet.xliff", """
                <xliff xmlns="urn:oasis:names:tc:xliff:document:2.0" version="2.0" srcLang="en">
