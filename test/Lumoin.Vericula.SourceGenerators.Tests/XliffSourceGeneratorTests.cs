                <xliff xmlns="urn:oasis:names:tc:xliff:document:2.0" version="2.0" srcLang="fr">
                  <file id="wallet"><unit id="Bonjour"><segment><source>Bonjour</source></segment></unit></file>
                </xliff>
                """)
        };

        GeneratorDriverRunResult result = RunGenerator(files, "Bootstrap", TestContext.CancellationToken);

        Assert.HasCount(1, result.Diagnostics);
