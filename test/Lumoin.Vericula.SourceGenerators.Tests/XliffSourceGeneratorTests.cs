    private static (Type TranslationsType, AssemblyLoadContext Context) EmitAndLoad(
        GeneratorDriverRunResult result,
        string assemblyName,
        int expectedDiagnosticCount,
        CancellationToken cancellationToken)
    {
        Assert.HasCount(expectedDiagnosticCount, result.Diagnostics);
        string code = result.Results[0].GeneratedSources[0].SourceText.ToString();
        var compilation = CSharpCompilation.Create(
            assemblyName: assemblyName,
            syntaxTrees: [CSharpSyntaxTree.ParseText(code, cancellationToken: cancellationToken)],
            references: NetReferences(),
            options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        using var peStream = new MemoryStream();
        EmitResult emitResult = compilation.Emit(peStream, cancellationToken: cancellationToken);
        Assert.IsTrue(emitResult.Success, string.Join(Environment.NewLine, emitResult.Diagnostics));

        peStream.Position = 0;
        var context = new AssemblyLoadContext(assemblyName, isCollectible: true);
        Assembly assembly = context.LoadFromStream(peStream);
        Type translationsType = assembly.GetType($"{assemblyName}.Localization.Translations")
            ?? throw new InvalidOperationException("The generated assembly does not declare a Translations type.");

        return (translationsType, context);
    }

    private static string Normalize(string text)
    {
        return text.Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static GeneratorDriverRunResult RunGenerator(string xliffContent, string assemblyName, CancellationToken cancellationToken)
    {
        return RunGenerator([("wallet.fi.xliff", xliffContent)], assemblyName, cancellationToken);
    }

    private static GeneratorDriverRunResult RunGenerator(IEnumerable<(string Path, string Content)> files, string assemblyName, CancellationToken cancellationToken)
    {
        var generator = new XliffSourceGenerator();
        var additionalTexts = files
            .Select(file => (AdditionalText)new MemoryAdditionalText(file.Path, file.Content))
            .ToArray();
        var driver = CSharpGeneratorDriver.Create(
            generators: [generator.AsSourceGenerator()],
            additionalTexts: additionalTexts);
        var compilation = CSharpCompilation.Create(
            assemblyName: assemblyName,
            syntaxTrees: [],
            references: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)]);

        //Kills the finding r-testquality-7 mutant: RunGenerators previously ran with no
        //cancellation token, so a hang inside generator execution would never be interrupted
        //by the test host's own timeout signal.
        return driver.RunGenerators(compilation, cancellationToken).GetRunResult();
    }

    private static List<MetadataReference> NetReferences()
    {
        string runtimeDirectory = global::System.Runtime.InteropServices.RuntimeEnvironment.GetRuntimeDirectory();

        return
        [
            MetadataReference.CreateFromFile(Path.Combine(runtimeDirectory, "System.Runtime.dll")),
            MetadataReference.CreateFromFile(Path.Combine(runtimeDirectory, "System.Collections.dll")),
            MetadataReference.CreateFromFile(Path.Combine(runtimeDirectory, "System.Globalization.dll")),
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location)
        ];
    }

    /// <summary>
    /// An <see cref="AdditionalText"/> backed by an in-memory string, so a generator test can hand
    /// the driver XLIFF content without touching disk.
    /// </summary>
    private sealed class MemoryAdditionalText: AdditionalText
    {
        /// <summary>
        /// Initializes a new instance carrying <paramref name="content"/> at <paramref name="path"/>.
        /// </summary>
        /// <param name="path">The additional text's path, as the generator sees it.</param>
        /// <param name="content">The additional text's content.</param>
        public MemoryAdditionalText(string path, string content)
        {
            Path = path;
            Content = content;
        }

        /// <summary>The additional text's path, as the generator sees it.</summary>
        public override string Path { get; }

        /// <summary>The additional text's content.</summary>
        private string Content { get; }

        /// <summary>
        /// Returns <see cref="Content"/> as a <see cref="SourceText"/>.
        /// </summary>
        /// <param name="cancellationToken">Unused; building the source text has no async path to cancel.</param>
        /// <returns>The additional text's content as source text.</returns>
        public override SourceText GetText(CancellationToken cancellationToken = default)
        {
            return SourceText.From(Content, Encoding.UTF8);
        }
    }
