            MetadataReference.CreateFromFile(Path.Combine(runtimeDirectory, "System.Collections.dll")),
            MetadataReference.CreateFromFile(Path.Combine(runtimeDirectory, "System.Globalization.dll")),
            MetadataReference.CreateFromFile(typeof(object).Assembly.Location)
        ];
    }

    /// <summary>
    /// An <see cref="AdditionalText"/> backed by an in-memory string, so a generator test can hand
    /// the driver XLIFF content without touching disk.
    /// </summary>
    private sealed class MemoryAdditionalText: AdditionalText
    {
        /// <summary>
        /// Initializes a new instance carrying <paramref name="content"/> at <paramref name="path"/>.
        /// </summary>
        /// <param name="path">The additional text's path, as the generator sees it.</param>
        /// <param name="content">The additional text's content.</param>
        public MemoryAdditionalText(string path, string content)
        {
            Path = path;
            Content = content;
        }

        /// <summary>The additional text's path, as the generator sees it.</summary>
        public override string Path { get; }

        /// <summary>The additional text's content.</summary>
        private string Content { get; }

        /// <summary>
        /// Returns <see cref="Content"/> as a <see cref="SourceText"/>.
        /// </summary>
        /// <param name="cancellationToken">Unused; building the source text has no async path to cancel.</param>
        /// <returns>The additional text's content as source text.</returns>
        public override SourceText GetText(CancellationToken cancellationToken = default)
        {
            return SourceText.From(Content, Encoding.UTF8);
        }
    }
