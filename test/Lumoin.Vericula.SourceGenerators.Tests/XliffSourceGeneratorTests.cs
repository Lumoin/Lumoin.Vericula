    private static GeneratorDriverRunResult RunGenerator(IEnumerable<(string Path, string Content)> files, string assemblyName, CancellationToken cancellationToken)
    {
        var generator = new XliffSourceGenerator();
        var additionalTexts = files
            .Select(file => (AdditionalText)new MemoryAdditionalText(file.Path, file.Content))
            .ToArray();
        var driver = CSharpGeneratorDriver.Create(
            generators: [generator.AsSourceGenerator()],
            additionalTexts: additionalTexts);
        var compilation = CSharpCompilation.Create(
            assemblyName: assemblyName,
            syntaxTrees: [],
            references: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)]);

        //Kills the finding r-testquality-7 mutant: RunGenerators previously ran with no
        //cancellation token, so a hang inside generator execution would never be interrupted
        //by the test host's own timeout signal.
        return driver.RunGenerators(compilation, cancellationToken).GetRunResult();
    }

    private static List<MetadataReference> NetReferences()
    {
