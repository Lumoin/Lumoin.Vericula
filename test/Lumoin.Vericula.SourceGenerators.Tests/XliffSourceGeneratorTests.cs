    [TestMethod]
    public void TheGeneratedSourceCompilesAndRunsUnderCSharp73()
    {
        //f-14: a netstandard2.0-targeting consumer with no explicit LangVersion defaults to C# 7.3.
        //The emitted class used to require C# 9 (target-typed `new`, nullable reference annotations,
        //the `is not null` pattern combinator), which fails at that language version with
        //CS8370-class errors - exactly the consumer scenario the generator, itself netstandard2.0,
        //is built to support. Parsing and compiling the generated source under
        //LanguageVersion.CSharp7_3 explicitly, then actually invoking an accessor, proves the
        //emitted code needs nothing newer.
        GeneratorDriverRunResult result = RunGenerator(TwoLanguageXliff, "Bootstrap73", TestContext.CancellationToken);
        Assert.HasCount(0, result.Diagnostics);
        string code = result.Results[0].GeneratedSources[0].SourceText.ToString();

        var parseOptions = new CSharpParseOptions(LanguageVersion.CSharp7_3);
        var compilation = CSharpCompilation.Create(
            assemblyName: "Bootstrap73",
            syntaxTrees: [CSharpSyntaxTree.ParseText(code, parseOptions, cancellationToken: TestContext.CancellationToken)],
            references: NetReferences(),
            options: new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        using var peStream = new MemoryStream();
        EmitResult emitResult = compilation.Emit(peStream, cancellationToken: TestContext.CancellationToken);
        Assert.IsTrue(emitResult.Success, string.Join(Environment.NewLine, emitResult.Diagnostics));

        peStream.Position = 0;
        var context = new AssemblyLoadContext("Bootstrap73", isCollectible: true);
        Assembly assembly = context.LoadFromStream(peStream);
        Type translationsType = assembly.GetType("Bootstrap73.Localization.Translations")
            ?? throw new InvalidOperationException("The generated assembly does not declare a Translations type.");

        //Resolve reads the real CurrentUICulture, so pin it to a culture unrelated to both "en"
        //(source) and "fi" (target) instead of trusting whatever the host machine's UI culture
        //happens to be, which would make this assertion pass or fail depending on where it runs.
        CultureInfo originalCulture = CultureInfo.CurrentUICulture;
        try
        {
            CultureInfo.CurrentUICulture = CultureInfo.GetCultureInfo("de");
            Assert.AreEqual("Your credentials, on your terms.", GetAccessor(translationsType, "HomeHeadline"));
        }
        finally
        {
            CultureInfo.CurrentUICulture = originalCulture;
        }

        context.Unload();
    }

