    [TestMethod]
    public void ADocumentWithADifferentSourceLanguageIsReportedAndExcludedRatherThanSilentlyFoldedIn()
    {
        //f-15: only the source-language table of valid[0] (the first document in path order) ever
        //got accessor properties; a second document's own srcLang units still landed in the internal
        //Languages dictionary with no accessor and no diagnostic - an inconsistent, silent partial
        //drop. The mismatched document must now be reported through VFX304 and excluded entirely:
        //no accessor, and none of its text lands in any generated table either.
        var files = new[]
        {
            ("a.xliff", """
