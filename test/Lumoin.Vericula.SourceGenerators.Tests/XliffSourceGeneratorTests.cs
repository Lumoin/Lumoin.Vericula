    private static string GetAccessor(Type translationsType, string propertyName)
    {
        PropertyInfo property = translationsType.GetProperty(propertyName, BindingFlags.Public | BindingFlags.Static)
            ?? throw new InvalidOperationException($"Translations does not declare a property named '{propertyName}'.");

        return (string)property.GetValue(null)!;
    }

