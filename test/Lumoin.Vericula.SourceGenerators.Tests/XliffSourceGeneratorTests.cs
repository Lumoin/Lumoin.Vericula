    [TestMethod]
    public void TheGeneratedSourceForTwoLanguagesMatchesTheGoldenOutput()
    {
        //Kills any mutant that changes BuildAccessorSource's formatting, dictionary
        //ordering, field naming or doc-comment text: an exact comparison notices any
        //byte that a substring check would have missed.
